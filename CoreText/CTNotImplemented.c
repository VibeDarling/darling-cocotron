// Names that cache frameworks import from CoreText and that Cocotron CoreText does not implement yet.
// Each one reports its name and aborts. Without a definition here dyld keeps the shared cache's own CoreText code for
// the name, which then runs on objects that Cocotron made and fails far from the cause, or worse, appears to work.
// Delete an entry when the function is implemented (a duplicate definition fails the link, which says so).
// The signatures are unknown on purpose: nothing returns.
// CTFontDescriptorCreateForUIType, CTFontCreateCopyOfSystemUIFontWithGrade and CTFontManagerUnregisterFontsForURL are left
// out: darling-cocotron #557 (feat/coretext-app-symbols-batch1) defines them. This branch is based on master, not on
// that one, so until #557 lands the three names fall through to the cache's CoreText code; #557 must land first.
#include <stdio.h>
#include <stdlib.h>

static void notImplemented(const char *name)
{
    fprintf(stderr, "CoreText: %s is not implemented by Cocotron CoreText\n", name);
    abort();
}

#define NOT_IMPLEMENTED(name) void name(void) { notImplemented(#name); }

